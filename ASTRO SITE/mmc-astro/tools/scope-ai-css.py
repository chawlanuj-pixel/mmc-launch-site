#!/usr/bin/env python3
"""One-off: namespace the standalone AI by MMC stylesheet under .ai-scope so it cannot leak into (or be broken by) the main site CSS.
Usage: python3 tools/scope-ai-css.py <ai.css> <out.css>
- :root / body / * rules map onto .ai-scope; html.<state> X maps to html.<state> .ai-scope X
- @media / @supports are recursed; @keyframes / @font-face are copied as is (keyframe names are prefixed ai- to avoid clashes)
- stand-in chrome rules (.nav, .pill, .sheet, .foot, .fab) are dropped: the real site shell supplies them."""
import re, sys
src = open(sys.argv[1]).read()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
DROP = re.compile(r"^\.(nav|pill|sheet|foot|fab)([\s_\-.:\[>+~,{]|$)")
kf = set(re.findall(r"@keyframes\s+([\w-]+)", src))

def split_top(s, sep):
    out, d, cur = [], 0, ""
    for ch in s:
        if ch in "([": d += 1
        elif ch in ")]": d -= 1
        if ch == sep and d == 0: out.append(cur); cur = ""
        else: cur += ch
    out.append(cur); return out

def scope_sel(sel):
    sel = sel.strip()
    if sel in (":root", "body", "html body"): return ".ai-scope"
    if sel == "*": return ".ai-scope, .ai-scope *"
    if sel == "html": return "html"
    m = re.match(r"^html((?:\.[\w-]+)+)\s*(.*)$", sel)
    if m:
        rest = m.group(2)
        if rest.startswith("body"): rest = rest[4:].strip()
        return "html" + m.group(1) + (" .ai-scope " + rest if rest else "")
    if sel.startswith("body"): return ".ai-scope" + sel[4:]
    return ".ai-scope " + sel

def fix_decl(body):
    for n in kf:
        body = re.sub(r"(animation(?:-name)?\s*:[^;}]*?)\b" + re.escape(n) + r"\b", lambda m: m.group(1) + "ai-" + n, body)
    return body

def parse(s):
    i, out = 0, []
    while i < len(s):
        j = s.find("{", i)
        if j < 0: break
        head = s[i:j].strip(); d, k = 1, j + 1
        while k < len(s) and d:
            d += (s[k] == "{") - (s[k] == "}"); k += 1
        body = s[j + 1:k - 1]; i = k
        if head.startswith("@keyframes"):
            out.append(head.replace("@keyframes ", "@keyframes ai-") + "{" + body + "}")
        elif head.startswith("@font-face"):
            out.append(head + "{" + body + "}")
        elif head.startswith("@"):
            out.append(head + "{" + parse(body) + "}")
        else:
            sels = [x.strip() for x in split_top(head, ",") if x.strip()]
            keep = [x for x in sels if not DROP.match(x)]
            if not keep: continue
            out.append(",".join(scope_sel(x) for x in keep) + "{" + fix_decl(body) + "}")
    return "\n".join(out)

res = parse(src)
res = re.sub(r"@media[^{]*\{\s*\}", "", res)
import os
here = os.path.dirname(os.path.abspath(__file__))
before = open(here + "/ai-extras-before.css").read()  # main-site isolation resets: must precede the AI rules so they can be overridden
after = open(here + "/ai-extras-after.css").read()    # integration additions (breadcrumb, anchor offset)
open(sys.argv[2], "w").write("/* AI by MMC, scoped under .ai-scope. Generated by tools/scope-ai-css.py from the standalone ai.css. */\n" + before + "\n" + res + "\n" + after)
print("rules written", res.count("{"))
