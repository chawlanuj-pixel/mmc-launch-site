// Writes public/_redirects from src/data/routes.json (old .html file -> clean route) plus ROLE-REDIRECTS.txt and the /insights/ alias.
// Run: node tools/build-redirects.mjs   (Netlify and Cloudflare Pages format; not read by Hostinger shared hosting)
import { readFileSync, writeFileSync } from "node:fs";
const routes = JSON.parse(readFileSync("src/data/routes.json", "utf8"));
const roles = readFileSync("ROLE-REDIRECTS.txt", "utf8").split("\n").filter((l) => l && !l.startsWith("#"));
const out = ["# Legacy and alias URLs to the canonical clean route (301). Generated by tools/build-redirects.mjs.", "/sitemap.xml /sitemap-index.xml 301"];
out.push("# /insights/ is not a page in V2; /guides/ is the hub (Insights.html already maps to /guides/ below).");
out.push("/insights /guides/ 301", "/insights/ /guides/ 301", "/insights/* /guides/:splat 301");
out.push("# Old careers detail addresses (query redirects first, then the bare address).", ...roles);
out.push("# Old .html pages");
for (const [file, to] of Object.entries(routes)) {
  if (file === "Job Detail.html") continue;
  out.push(`/${file.replace(/ /g, "%20")} ${to} 301`);
  if (file === "index.html") continue;
  if (file.includes(" ")) out.push(`/${file} ${to} 301`);
}
writeFileSync("public/_redirects", out.join("\n") + "\n");
console.log("wrote", out.length, "lines");
